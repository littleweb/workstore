import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';
import {buildSync} from 'esbuild';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'../..');
const ajv=new Ajv({allErrors:true,code:{source:true}});
const check=ajv.compile(JSON.parse(readFileSync(`${root}/schemas/comic-template.schema.json`,'utf8')));
buildSync({stdin:{contents:standalone(ajv,check),resolveDir:root,loader:'js'},bundle:true,platform:'browser',format:'esm',outfile:`${root}/src/comics/template-validator.js`,banner:{js:'// Generated by scripts/comics/build-validator.mjs; no runtime eval (desktop CSP).'}});
