/** Independent editorial rules inspired by xiaohongshu-creator's title workflow.
 * No vendor API, popularity scores, telemetry, or additional model requests.
 */
export function titleStrategy(stage: 'cover' | 'publishing') {
  const target = stage === 'cover'
    ? '封面标题方案由title和text组成：中文title最多10字、text最多20字，英文分别最多60、100字符。title可简短，text补充阅读疑问或收益，不机械截断长标题，也不把同一句话重复两遍。仅将选中的方案写入pages[0]。'
    : '主标题和备选标题均最多20个字符，严格使用配置语言。只将选中的主标题及两个不同切入点的备选写入title和alternatives，不新增输出字段。';
  return `后台标题策划（在当前请求内完成，不增加用户步骤）：
从实际漫画内容提取核心主题词、目标读者、具体场景、关键事件、读者疑问与能兑现的阅读回报。保持主题边界，例如“沙坡头的来历”不能包装成游玩攻略；不从题材自行推导正文没有的方法、事实或效果。
内部拟出约六个标题候选，按题材从疑问、具体场景、反差、故事悬念、知识收益和新观察中选择不同角度。候选不是同一句话的同义改写，也不强制凑齐六种套路：知识漫画优先明确问题，生活故事优先真实场景，安静/文学作品允许含蓄表达。
逐个检查主题准确、表达具体、陌生读者能理解、好奇或收益明确、正文实际兑现和长度合格。为选择提供内容中的事件、台词或知识点证据，不计算爆款概率、市场排名或虚假的匹配指数；没有外部样本时不声称依据近期热点/高赞数据。
优先选能体现作品独特内容的标题，避免泛泛“你一定要知道”、生硬热词、虚假亲历、无依据数字、制造焦虑、夸张效果和照抄他人标题。不强制emoji、数字、感叹号或反转；传说不能写成已证实史实，故事不能冒充育儿/医疗等建议。
${target}
封面与发布标题可采用不同措辞，但提出的期待必须由同一套正文兑现。候选、评选过程和证据只在内部比较，不进入封面画面、对白、发布正文或标签。用户明确指定标题/文字时优先保留；超长时遵循现有字数限制精简，不擅自替换核心含义。`;
}
